"""WP3b: which G4 impairment breaks the estimator? Per-impairment ablation on CALIBRATION seeds (never scored).

    python -m experiments.readiness.ablation [--stride 2] [--workers 8]
    -> artifacts/readiness/ablation.json, docs/reports/ABLATION.md

Every capture is drawn from the same seed with a different set of impairments switched on (the generator makes every random
draw regardless, so runs are paired). Conditions: none, all (= G4), each impairment alone, and all-but-one. Each capture goes
through the product path (Detect, then the verify estimator on the matched candidate) via `systems.run`. Uses G4 calibration
seeds only; the scoreboard's refusal to touch them is mirrored here in reverse: this tool refuses the test seeds.
"""
import argparse
import json
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

from . import generators, impaired, systems
from .metrics import label_matches

ROOT = Path(__file__).resolve().parents[2]
OUT_JSON = ROOT / "artifacts" / "readiness" / "ablation.json"
OUT_MD = ROOT / "docs" / "reports" / "ABLATION.md"


def conditions():
    out = [("none", ()), ("all", impaired.IMPAIRMENTS)]
    out += [(f"only:{k}", (k,)) for k in impaired.IMPAIRMENTS]
    out += [(f"without:{k}", tuple(x for x in impaired.IMPAIRMENTS if x != k)) for k in impaired.IMPAIRMENTS]
    return out


def width_ratio(row):
    """Width of the Detect band that best overlaps the true band, over the true occupied width (None if unavailable)."""
    band = row["truth"].get("band")
    bands = (row.get("detect") or {}).get("bands")
    if not band or not bands:
        return None
    lo, hi = band
    best = max(bands, key=lambda b: max(0.0, min(b[1], hi) - max(b[0], lo)))
    if max(0.0, min(best[1], hi) - max(best[0], lo)) == 0:
        return None
    return (best[1] - best[0]) / (hi - lo)


def compact(row):
    w = width_ratio(row)
    return dict(truth=row["truth"]["label"], label=row["out"]["label"], tier=row["out"].get("tier"),
                width_ratio=None if w is None else round(w, 3), n_overlap=(row.get("detect") or {}).get("n_overlap"))


def summarize(rows):
    n = len(rows)
    lab = [r["out"]["label"] for r in rows]
    truth = [r["truth"]["label"] for r in rows]
    correct = sum(label_matches(l, t) for l, t in zip(lab, truth))
    wrong = sum(l is not None and not label_matches(l, t) for l, t in zip(lab, truth))
    lib = [(l, t) for l, t, r in zip(lab, truth, rows) if r["truth"].get("in_library")]
    wr = [w for w in (width_ratio(r) for r in rows) if w is not None]
    ok = [r for r in rows if (width_ratio(r) is not None and 0.5 <= width_ratio(r) <= 2)]
    return dict(ok_bounds=len(ok) / n,
                correct_given_ok_bounds=sum(label_matches(r["out"]["label"], r["truth"]["label"]) for r in ok) / len(ok) if ok else None,
                too_wide=sum(w > 2 for w in wr) / len(wr) if wr else None,
                too_narrow=sum(w < 0.5 for w in wr) / len(wr) if wr else None,
                n=n, correct_in_library=sum(label_matches(l, t) for l, t in lib) / len(lib) if lib else None, correct=correct / n, wrong=wrong / n, abstain=sum(l is None for l in lab) / n,
                unknown_tier=sum(r["out"].get("tier") == "unknown_family" for r in rows) / n,
                fragmented=sum(bool(r["detect"]) and r["detect"]["n_overlap"] > 1 for r in rows) / n,
                detect_miss=sum(bool(r["detect"]) and not r["detect"]["hit"] for r in rows) / n)


def _one(job):
    spec, impairments = job
    cap = generators.g4_capture(**spec, impairments=impairments)
    return systems.run("verify", cap)


def run(seed_base, stride, workers):
    specs = [s for s in generators.g4_specs(seed_base)[::stride] if s["kind"] != "noise"]
    result = {}
    with ProcessPoolExecutor(workers) as ex:
        for name, imp in conditions():
            rows = list(ex.map(_one, [(s, imp) for s in specs], chunksize=4))
            result[name] = dict(summary=summarize(rows), impairments=list(imp), rows=[compact(r) for r in rows])
            s = result[name]["summary"]
            print(f"{name:22s} n={s['n']} correct {s['correct']:.1%} wrong {s['wrong']:.1%} abstain {s['abstain']:.1%} "
                  f"unknown-tier {s['unknown_tier']:.1%}", flush=True)
    return specs, result


def render(result, n, seed_base, stride):
    base, none = result["all"]["summary"], result["none"]["summary"]
    lines = ["# G4 per-impairment ablation (generated by `experiments/readiness/ablation.py`)\n",
             f"{n} non-noise G4 captures drawn from **calibration** seeds {seed_base}+ (every {stride}nd of the grid); "
             "same seed in every row, one product path (Detect + verify). Diagnostic only: nothing here is scored.\n",
             "| condition | correct (all) | wrong | abstain | unknown tier | fragmented | Detect miss | band > 2x true | bounds ok | correct given ok bounds |", "|---|---|---|---|---|---|---|---|---|---|"]
    for name, r in result.items():
        s = r["summary"]
        lines.append(f"| {name} | {s['correct']:.1%} | {s['wrong']:.1%} | {s['abstain']:.1%} | {s['unknown_tier']:.1%} | "
                     f"{s['fragmented']:.1%} | {s['detect_miss']:.1%} | {s['too_wide']:.1%} | {s['ok_bounds']:.1%} | {s['correct_given_ok_bounds']:.1%} |")
    lines += ["", f"Unimpaired ceiling (`none`): {none['correct']:.1%} correct. Full G4 (`all`): {base['correct']:.1%} correct.\n",
              "Cost of each impairment = correct(none) - correct(only:X); recovery = correct(without:X) - correct(all).\n",
              "| impairment | cost when alone | recovery when removed |", "|---|---|---|"]
    for k in impaired.IMPAIRMENTS:
        cost = none["correct"] - result[f"only:{k}"]["summary"]["correct"]
        rec = result[f"without:{k}"]["summary"]["correct"] - base["correct"]
        lines.append(f"| {k} | {100 * cost:+.1f} points | {100 * rec:+.1f} points |")
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed-base", type=int, default=generators.G4_CALIBRATION_SEED_BASE)
    ap.add_argument("--stride", type=int, default=2)
    ap.add_argument("--workers", type=int, default=8)
    args = ap.parse_args(argv)
    if args.seed_base != generators.G4_CALIBRATION_SEED_BASE:
        raise SystemExit("the ablation runs on G4 calibration seeds only")
    specs, result = run(args.seed_base, args.stride, args.workers)
    OUT_JSON.write_text(json.dumps(dict(n=len(specs), seed_base=args.seed_base, stride=args.stride, conditions=result), indent=1) + "\n")
    OUT_MD.write_text(render(result, len(specs), args.seed_base, args.stride))
    print("wrote", OUT_MD)


if __name__ == "__main__":
    main()
