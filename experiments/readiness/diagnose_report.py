"""WP3: turn artifacts/readiness/{diagnosis,fsk_split_probe,oracle_bounds}.json into docs/reports/WP3_tables.md.

    python -m experiments.readiness.diagnose_report

Pure aggregation of what diagnose.py, fsk_split_probe.py and oracle_bounds.py recorded; no analysis runs here.
A file's *primary* candidate is its highest-SNR Detect candidate (RC1-RC3 themselves score a file by ANY candidate).
"""
import collections
import json
import re
import statistics as st
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ART = ROOT / "artifacts" / "readiness"
OUT = ROOT / "docs" / "reports" / "WP3_tables.md"


def load(name):
    return json.loads((ART / name).read_text())


def fs_of(stem):
    m = re.search(r"_(\d+(?:_\d)?)k(?:$|_)", stem)
    return float(m.group(1).replace("_", ".")) * 1e3 if m else None


def table(header, rows):
    return "\n".join(["| " + " | ".join(header) + " |", "|" + "---|" * len(header)] +
                     ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def counts(counter, total=None):
    return table(["cause", "n", "share"], [(k, v, f"{v / (total or sum(counter.values())):.0%}") for k, v in counter.most_common()])


def primary_cause(r):
    if r.get("cause") == "pulsed":
        cf = r.get("counterfactual") or {}
        return "pulsed refusal -> if lifted: " + (cf.get("outcome") or "?") + (f" ({cf['label']})" if cf.get("label") else "")
    return r.get("cause") or ("correct label" if r["correct"] else f"WRONG label ({r['label']})")


def evidence_str(r):
    ev = r.get("evidence") or (r.get("counterfactual") or {}).get("evidence")
    if not ev:
        return ""
    return f"best {ev['best'][1]}/{ev['best'][0]}; m_fam {ev['m_fam']:.2f}; m_label {ev['m_label']:.2f}; unexpl {ev['unexplained']:.2f}; n {ev['samples']}"


def build():
    d = load("diagnosis.json")
    real, g4 = d["real"], d["g4"]
    md = ["# WP3 tables (generated by `experiments/readiness/diagnose_report.py`; do not edit by hand)\n"]
    files = collections.defaultdict(list)
    for r in real:
        files[r["file"]].append(r)
    prim = {f: max(rs, key=lambda r: r["snr_db"] if r["snr_db"] is not None else -99) for f, rs in files.items()}

    md.append(f"## Coverage\n\n{len(files)} files (6 G3 + 87 G5 test), {len(real)} Detect candidates; G4 sample: {len(g4)} non-noise captures "
              f"(every 3rd of the 336 test captures).\n")
    md.append("## A. Every candidate, first failing gate (real files)\n")
    for s in ("G3", "G5"):
        c = collections.Counter(r.get("cause") or ("correct label" if r["correct"] else "WRONG label") for r in real if r["set"] == s)
        md.append(f"**{s}**\n\n" + counts(c) + "\n")
    md.append("## B. Each file's primary (highest-SNR) candidate\n")
    md.append(counts(collections.Counter(primary_cause(r) for r in prim.values())) + "\n")

    md.append("## C. Per-file table (primary candidate)\n")
    rows = []
    for f, r in sorted(prim.items(), key=lambda kv: (kv[1]["set"], kv[0])):
        cf = r.get("counterfactual") or {}
        fs = fs_of(f)
        burst = f"{cf['longest_burst_samples'] / fs * 1e3:.1f} ms x{cf['bursts']}" if cf and fs and cf.get("longest_burst_samples") else ""
        rows.append((r["set"], f[:44], "/".join(r["truth"]) or "none", r.get("coding") or "", len(files[f]),
                     f"{r['snr_db']:.0f}" if r["snr_db"] is not None else "", primary_cause(r), burst, evidence_str(r)))
    md.append(table(["set", "file", "truth", "coding", "cands", "SNR dB", "primary: cause", "longest burst x bursts", "evidence (verify on it)"], rows) + "\n")

    md.append("## D. Wrong labels published on real files (all candidates)\n")
    w = [r for r in real if r["wrong"]]
    md.append(table(["file", "truth", "said", "rate said / expected", "SNR dB", "m_fam (=m_label)", "unexplained"],
                    [(r["file"][:44], "/".join(r["truth"]), r["label"],
                      f"{r['rate']:.0f} / {r['expected_rate']:.0f}" if r["rate"] and r["expected_rate"] else "-",
                      f"{r['snr_db']:.1f}", f"{r['evidence']['m_fam']:.2f}", f"{r['evidence']['unexplained']:.3f}") for r in w]) + "\n")
    md.append(f"{len(w)} wrong detections; {sum(1 for r in w if r['snr_db'] is not None and r['snr_db'] >= 15)} at >= 15 dB SNR. "
              f"Margin thresholds: m_fam >= 0.168, m_label >= 0.183, unexplained <= 0.119 (nats per sample).\n")

    md.append("## E. What lifting the pulsed refusal would do (counterfactual on the longest burst)\n")
    cf = [r for r in real if r.get("counterfactual")]
    md.append(counts(collections.Counter(r["counterfactual"]["outcome"] for r in cf)) + "\n")
    lab = collections.Counter((r["truth"][0] if r["truth"] else "none", r["counterfactual"]["label"]) for r in cf if r["counterfactual"].get("label"))
    md.append(f"Published if lifted: {sum(r['counterfactual_correct'] for r in cf)} correct, {sum(r['counterfactual_wrong'] for r in cf)} wrong "
              f"(truth, label): {dict(lab)}\n")
    lb = [r["counterfactual"]["longest_burst_samples"] for r in cf]
    md.append(f"Longest burst: median {st.median(lb):.0f} samples, minimum {min(lb)}. Verify needs >= 2000 raw samples.\n")

    probe = [p for p in load("fsk_split_probe.json") if p["ratio"] is not None]
    md.append("## F. Detect bounds on FSK2 files: candidate bandwidth / tone split of the file's strongest burst\n")
    md.append(table(["file", "tone split kHz", "top candidate bw kHz", "ratio", "candidates within 3 dB SNR"],
                    [(p["file"][:44], f"{p['split_khz']:.1f}", f"{p['bw_khz']:.1f}", f"{p['ratio']:.2f}", p["n_near"]) for p in probe]) + "\n")
    md.append(f"{len(probe)} files: candidate narrower than half the split on {sum(p['ratio'] < 0.5 for p in probe)}; "
              f"between half and twice the split on {sum(0.5 <= p['ratio'] <= 2 for p in probe)}; wider than twice the split on {sum(p['ratio'] > 2 for p in probe)}.\n")

    orc = [o for o in load("oracle_bounds.json") if o.get("outcome") != "skipped_too_long"]
    md.append("## G. Oracle experiment: strongest packet, sane band, not refused (upper bound, not a product path)\n")
    for truth in ("ASK2", "FSK2"):
        r = [o for o in orc if o["truth"] == truth]
        md.append(f"**{truth}** (n={len(r)}): {sum(o['correct'] for o in r)} correct label, {sum(o['wrong'] for o in r)} wrong; "
                  f"abstain causes {dict(collections.Counter(o.get('cause') for o in r if not o.get('label')))}\n")
    md.append(table(["file", "truth", "label", "rate out / expected", "cause if abstained"],
                    [(o["file"][:44], o["truth"], o.get("label") or "-",
                      f"{o['rate_out']:.0f} / {o['rate']:.0f}" if o.get("rate_out") else f"- / {o['rate']:.0f}", o.get("cause") or "") for o in orc]) + "\n")

    md.append("## H. G4 (impaired synthetic) sample\n")
    c = collections.Counter(r.get("cause") or ("correct label" if r.get("correct") else "WRONG label") for r in g4)
    md.append(counts(c) + "\n")
    fam = collections.defaultdict(collections.Counter)
    for r in g4:
        fam[r["truth"][0]][r.get("cause") or ("OK" if r.get("correct") else "WRONG:" + str(r["label"]))] += 1
    md.append(table(["truth", "n", "causes"], [(k, sum(v.values()), dict(v)) for k, v in sorted(fam.items())]) + "\n")
    rows = []
    for lo, hi in ((-99, 5), (5, 10), (10, 15), (15, 99)):
        rs = [r for r in g4 if lo <= (r["snr_db"] if r.get("snr_db") is not None else 99) < hi]
        rows.append((f"{lo if lo > -99 else '<'}..{hi if hi < 99 else '>'} dB", len(rs), f"{sum(1 for r in rs if not r.get('label')) / len(rs):.0%}",
                     f"{sum(r.get('correct', False) for r in rs) / len(rs):.0%}",
                     dict(collections.Counter(r.get("cause") for r in rs if r.get("cause")))))
    md.append(table(["SNR band", "n", "abstained", "correct", "abstain causes"], rows) + "\n")
    wr = [r["width_ratio"] for r in g4 if "width_ratio" in r]
    md.append(f"Detect bounds vs true occupied width: median {st.median(wr):.2f}, p10 {sorted(wr)[len(wr) // 10]:.2f}, p90 {sorted(wr)[9 * len(wr) // 10]:.2f}; "
              f">2x wide on {sum(w > 2 for w in wr)}/{len(wr)}, <0.5x on {sum(w < 0.5 for w in wr)}/{len(wr)}; detections overlapping the true band "
              f"{dict(collections.Counter(r.get('n_overlap') for r in g4))}; Detect misses {sum(1 for r in g4 if r.get('cause') == 'detect_miss')}.\n")
    un = [r["evidence"]["unexplained"] for r in g4 if r.get("cause") == "unexplained" and r.get("evidence")]
    mf = [r["evidence"]["m_fam"] for r in g4 if r.get("cause") == "m_fam" and r.get("evidence")]
    md.append(f"unexplained abstentions: median {st.median(un):.2f} (limit 0.119); m_fam abstentions: median {st.median(mf):.3f} (threshold 0.168).\n")
    md.append("**G4 wrong labels**\n\n" + table(["capture", "truth", "said", "SNR dB", "in library", "m_fam", "unexplained"],
              [(r["file"], r["truth"][0], r["label"], f"{r['snr_db']:.0f}", r["in_library"], f"{r['evidence']['m_fam']:.2f}",
                f"{r['evidence']['unexplained']:.3f}") for r in g4 if r.get("wrong")]) + "\n")

    ok = [r["evidence"]["m_fam"] for r in g4 + real if r.get("correct") and r.get("evidence")]
    bad = [r["evidence"]["m_fam"] for r in g4 + real if r.get("wrong") and r.get("evidence")]
    auc = sum((a > b) + 0.5 * (a == b) for a in ok for b in bad) / (len(ok) * len(bad))
    md.append(f"## I. Do margins separate right from wrong?\n\nPooled G4 sample + real files: {len(ok)} correct vs {len(bad)} wrong published labels; "
              f"AUC of m_fam (correct ranked above wrong) = {auc:.2f} (0.5 = no information). Small n: treat as a warning, not a measurement.\n")
    OUT.write_text("\n".join(md) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    build()
